// Invoke searches one bounded inbound activity page.
func (operation ListInboundMessagesOperation) Invoke(call sdkgo.Call, input ListInboundMessagesInput) sdkgo.QueryAttempt[InboundMessagePage] {
	if input.Count == 0 {
		input.Count = 50
	}
	if input.Count < 1 || input.Count > 500 || input.Offset < 0 || input.Count+input.Offset > 10000 || !validInboundStatus(input.Status) {
		return queryFailure[InboundMessagePage]("listInboundMessages", ListInboundMessagesBranchDefect, sdkgo.FailureValidation, "count, offset, or inbound status is invalid")
	}
	query := url.Values{"count": {strconv.Itoa(input.Count)}, "offset": {strconv.Itoa(input.Offset)}}
	if input.Status != "" {
		query.Set("status", input.Status)
	}
	return runQuery(operation.client, call, "listInboundMessages", "/messages/inbound?"+query.Encode(), ListInboundMessagesBranchListed, "", ListInboundMessagesBranchProviderRejected, ListInboundMessagesBranchInvalidResponse, ListInboundMessagesBranchDefect, func(body []byte) (InboundMessagePage, error) {
		var page InboundMessagePage
		err := json.Unmarshal(body, &page)
		if err == nil && page.Messages == nil {
			err = fmt.Errorf("inbound messages missing")
		}
		return page, err
	})
}

// Invoke retrieves metadata for one inbound message.
func (operation GetInboundMessageDetailsOperation) Invoke(call sdkgo.Call, input GetInboundMessageDetailsInput) sdkgo.QueryAttempt[InboundMessage] {
	if strings.TrimSpace(input.MessageID) == "" {
		return queryFailure[InboundMessage]("getInboundMessageDetails", GetInboundMessageDetailsBranchDefect, sdkgo.FailureValidation, "message ID is required")
	}
	return runQuery(operation.client, call, "getInboundMessageDetails", "/messages/inbound/"+url.PathEscape(input.MessageID)+"/details", GetInboundMessageDetailsBranchFound, GetInboundMessageDetailsBranchNotFound, GetInboundMessageDetailsBranchProviderRejected, GetInboundMessageDetailsBranchInvalidResponse, GetInboundMessageDetailsBranchDefect, decodeInboundMessage)
}

// Invoke requests processing of one blocked inbound message.
func (operation BypassInboundMessageOperation) Invoke(call sdkgo.Call, input InboundMessageActionInput) sdkgo.MutationAttempt[InboundMessageAction] {
	return operation.client.actOnInboundMessage(call, "bypassInboundMessage", input, "bypass", "Blocked", BypassInboundMessageDefinition.StepDefaults.ExecuteMethodTimeout, BypassInboundMessageBranchBypassed, BypassInboundMessageBranchProviderRejected, BypassInboundMessageBranchDefect)
}

// Invoke reschedules one failed inbound message.
func (operation RetryInboundMessageOperation) Invoke(call sdkgo.Call, input InboundMessageActionInput) sdkgo.MutationAttempt[InboundMessageAction] {
	return operation.client.actOnInboundMessage(call, "retryInboundMessage", input, "retry", "Failed", RetryInboundMessageDefinition.StepDefaults.ExecuteMethodTimeout, RetryInboundMessageBranchRetried, RetryInboundMessageBranchProviderRejected, RetryInboundMessageBranchDefect)
}

func validInboundStatus(status string) bool {
	switch status {
	case "", "blocked", "processed", "queued", "failed", "scheduled":
		return true
	default:
		return false
	}
}

func decodeInboundMessage(body []byte) (InboundMessage, error) {
	var message InboundMessage
	err := json.Unmarshal(body, &message)
	if err == nil && message.MessageID == "" {
		err = fmt.Errorf("inbound message ID missing")
	}
	return message, err
}

func (client *Client) actOnInboundMessage(call sdkgo.Call, operation string, input InboundMessageActionInput, action, previousStatus string, timeout time.Duration, success, rejected, defect sdkgo.BranchID) sdkgo.MutationAttempt[InboundMessageAction] {
	if strings.TrimSpace(input.MessageID) == "" {
		return mutationFailure[InboundMessageAction](operation, defect, sdkgo.FailureValidation, "message ID is required")
	}
	fence, err := singledispatch.NewFence(call, timeout, singledispatch.WithMaxSends(call.MaxSends()))
	if err != nil {
		return mutationFailure[InboundMessageAction](operation, defect, sdkgo.FailureLocalDefect, "inbound dispatch fence is unavailable")
	}
	decision := fence.Decide()
	if decision.Kind == singledispatch.FailClosed {
		return sdkgo.NewMutationUncertain(InboundMessageAction{}, newFailure(operation, sdkgo.FailureTransport, "inbound dispatch checkpoint cannot be read"), sdkgo.Receipt{})
	}
	if decision.Kind != singledispatch.SendAllowed {
		confirmed, readErr := client.confirmInboundAction(call, input.MessageID, previousStatus)
		if readErr != nil {
			return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureAvailability, "inbound status could not be checked"), 0)
		}
		if confirmed {
			return sdkgo.NewMutationBranch(success, InboundMessageAction{MessageID: input.MessageID, Accepted: true}, nil, sdkgo.Receipt{})
		}
		if decision.Kind == singledispatch.ReadBackRequired {
			return sdkgo.NewMutationUncertain(InboundMessageAction{}, newFailure(operation, sdkgo.FailureTransport, "inbound action may have succeeded but could not be confirmed"), sdkgo.Receipt{})
		}
	}
	request, err := client.newRequest(call, http.MethodPut, "/messages/inbound/"+url.PathEscape(input.MessageID)+"/"+action, []byte{})
	if err != nil {
		if decision.MaximumPriorSends > 0 {
			return sdkgo.NewMutationUncertain(InboundMessageAction{}, newFailure(operation, sdkgo.FailureAuthentication, "an earlier inbound action may have succeeded"), sdkgo.Receipt{})
		}
		return mutationFailure[InboundMessageAction](operation, defect, sdkgo.FailureAuthentication, "connection credentials or request are invalid")
	}
	var response *http.Response
	err = fence.Dispatch(func(requestContext context.Context) error {
		var sendErr error
		response, sendErr = client.httpClient.Do(request.WithContext(requestContext))
		return sendErr
	})
	if errors.Is(err, singledispatch.ErrCheckpoint) || errors.Is(err, singledispatch.ErrInsufficientTime) {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureAvailability, "inbound dispatch did not start"), 0)
	}
	if err != nil {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureTransport, "inbound action outcome is unknown"), 0)
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode == http.StatusTooManyRequests || response.StatusCode == http.StatusServiceUnavailable {
		if err := fence.RecordCanResend(); err != nil {
			return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureAvailability, "inbound retry checkpoint failed"), 0)
		}
		kind := sdkgo.FailureAvailability
		if response.StatusCode == http.StatusTooManyRequests {
			kind = sdkgo.FailureRateLimit
		}
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, kind, "Postmark temporarily refused inbound action"), providerhttp.ParseRetryAfter(response.Header.Get("Retry-After"), time.Now()))
	}
	if response.StatusCode >= 500 || response.StatusCode == http.StatusRequestTimeout {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureAvailability, "inbound action outcome is unknown"), 0)
	}
	if response.StatusCode != http.StatusOK {
		if decision.MaximumPriorSends > 0 {
			return sdkgo.NewMutationUncertain(InboundMessageAction{}, newFailure(operation, sdkgo.FailureProviderRejection, "a prior inbound action may have succeeded"), sdkgo.Receipt{})
		}
		return mutationFailure[InboundMessageAction](operation, rejected, sdkgo.FailureProviderRejection, "Postmark refused inbound action")
	}
	content, err := providerhttp.ReadBoundedBody(response.Body, client.maxResponseBytes)
	if err != nil {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureTransport, "inbound acceptance response was interrupted"), 0)
	}
	var outcome struct {
		ErrorCode int    `json:"ErrorCode"`
		Message   string `json:"Message"`
	}
	if err := json.Unmarshal(content, &outcome); err != nil || outcome.ErrorCode != 0 || outcome.Message == "" {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureProtocol, "inbound acceptance response was incomplete"), 0)
	}
	if err := fence.RecordProviderID(input.MessageID); err != nil {
		return sdkgo.NewMutationRetry[InboundMessageAction](newFailure(operation, sdkgo.FailureAvailability, "accepted inbound checkpoint could not be recorded"), 0)
	}
	return sdkgo.NewMutationBranch(success, InboundMessageAction{MessageID: input.MessageID, Accepted: true}, nil, sdkgo.Receipt{})
}

func (client *Client) confirmInboundAction(call sdkgo.Call, messageID, previousStatus string) (bool, error) {
	request, err := client.newRequest(call, http.MethodGet, "/messages/inbound/"+url.PathEscape(messageID)+"/details", nil)
	if err != nil {
		return false, err
	}
	response, err := client.httpClient.Do(request)
	if err != nil {
		return false, err
	}
	defer func() { _ = response.Body.Close() }()
	if response.StatusCode != http.StatusOK {
		return false, fmt.Errorf("inbound lookup returned HTTP %d", response.StatusCode)
	}
	content, err := providerhttp.ReadBoundedBody(response.Body, client.maxResponseBytes)
	if err != nil {
		return false, err
	}
	message, err := decodeInboundMessage(content)
	if err != nil {
		return false, err
	}
	return message.MessageID == messageID && message.Status != "" && !strings.EqualFold(message.Status, previousStatus), nil
}
