// InboundMessage contains inbound activity metadata without message bodies or attachments.
type InboundMessage struct {
	// MessageID identifies the provider message.
	MessageID string `json:"MessageID"`
	// From is the sender address.
	From string `json:"From"`
	// To is the receiving address.
	To string `json:"To"`
	// Subject is the email subject.
	Subject string `json:"Subject"`
	// Status is the provider's processing state.
	Status string `json:"Status"`
	// BlockedReason describes a provider rule, when present.
	BlockedReason string `json:"BlockedReason,omitempty"`
}

// InboundMessagePage is one bounded inbound activity page.
type InboundMessagePage struct {
	// TotalCount is the count of matching messages.
	TotalCount int `json:"TotalCount"`
	// Messages contains the requested page.
	Messages []InboundMessage `json:"InboundMessages"`
}

// ListInboundMessagesInput chooses a bounded inbound search page.
type ListInboundMessagesInput struct {
	// Count is the page size, up to 500; zero selects 50.
	Count int `json:"count,omitempty"`
	// Offset is the zero-based page offset.
	Offset int `json:"offset,omitempty"`
	// Status optionally filters to blocked, processed, queued, failed, or scheduled messages.
	Status string `json:"status,omitempty"`
}

// GetInboundMessageDetailsInput identifies one inbound message.
type GetInboundMessageDetailsInput struct {
	// MessageID is the provider inbound message identity.
	MessageID string `json:"messageId"`
}

// InboundMessageActionInput identifies a blocked or failed inbound message.
type InboundMessageActionInput struct {
	// MessageID is the provider inbound message identity.
	MessageID string `json:"messageId"`
}

// InboundMessageAction confirms a provider processing request.
type InboundMessageAction struct {
	// MessageID is the requested provider message identity.
	MessageID string `json:"messageId"`
	// Accepted is true when Postmark confirms the bypass or retry.
	Accepted bool `json:"accepted"`
}

// ListInboundMessagesOperation searches inbound activity.
type ListInboundMessagesOperation struct{ client *Client }

// GetInboundMessageDetailsOperation retrieves inbound metadata.
type GetInboundMessageDetailsOperation struct{ client *Client }

// BypassInboundMessageOperation bypasses a provider rule for one blocked message.
type BypassInboundMessageOperation struct{ client *Client }

// RetryInboundMessageOperation reschedules one failed inbound message.
type RetryInboundMessageOperation struct{ client *Client }

