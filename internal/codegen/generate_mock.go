const (
	// MockOutputFile is the generated mock package source, in the connector's MockPackageName directory.
	MockOutputFile = "zz_generated_mock.go"
	// MockTestOutputFile is the generated test that decodes every manifest mock strictly.
	MockTestOutputFile = "zz_generated_mock_test.go"
)

// failureKindConstants maps each schema.FailureKinds wire value to its Connector SDK constant.
var failureKindConstants = map[string]string{
	"VALIDATION": "FailureValidation", "AUTHENTICATION": "FailureAuthentication", "AUTHORIZATION": "FailureAuthorization",
	"NOT_FOUND": "FailureNotFound", "CONFLICT": "FailureConflict", "RATE_LIMIT": "FailureRateLimit",
	"QUOTA_EXHAUSTED": "FailureQuotaExhausted", "AVAILABILITY": "FailureAvailability",
	"PROVIDER_REJECTION": "FailureProviderRejection", "TRANSPORT": "FailureTransport",
	"RESPONSE_TOO_LARGE": "FailureResponseTooLarge", "PROTOCOL": "FailureProtocol", "LOCAL_DEFECT": "FailureLocalDefect",
}

// MockPackageName returns the generated mock package name and directory, such as llmmock for package llm.
func MockPackageName(manifest schema.Manifest) string {
	return manifest.Spec.Codegen.Go.Package + "mock"
}

// GenerateMockPackage returns the mock package source and its test for a manifest that declares mocks.
// connectorImportPath is the Go import path of the connector package.
func GenerateMockPackage(manifest schema.Manifest, connectorImportPath string) ([]byte, []byte, error) {
	if !manifest.HasMocks() {
		return nil, nil, fmt.Errorf("manifest %s declares no mocks", manifest.Metadata.Name)
	}
	mockGeneration := &mockGenerator{manifest: manifest, connectorPackage: manifest.Spec.Codegen.Go.Package, identifiers: map[string]bool{}}
	source, err := mockGeneration.generateSource(connectorImportPath)
	if err != nil {
		return nil, nil, err
	}
	test, err := mockGeneration.generateTest(connectorImportPath)
	if err != nil {
		return nil, nil, err
	}
	return source, test, nil
}

type mockGenerator struct {
	manifest         schema.Manifest
	connectorPackage string
	identifiers      map[string]bool
}

func (mockGeneration *mockGenerator) generateSource(connectorImportPath string) ([]byte, error) {
	generation := &generator{}
	manifest := mockGeneration.manifest
	connector := mockGeneration.connectorPackage
	generation.mustWrite("// Code generated by connectorctl generate; DO NOT EDIT.\n")
	generation.mustWrite("// Copyright (c) 2026 Super Durable\n// SPDX-License-Identifier: MIT\n\n")
	generation.mustWrite("// Package %s scripts the %s connector's operations in application tests. New returns a\n", MockPackageName(manifest), manifest.Metadata.Name)
	generation.mustWrite("// Connection whose operations answer from connectormock scripts, with each query's manifest default installed.\n")
	generation.mustWrite("package %s\n\n", MockPackageName(manifest))
	generation.mustWrite("import (\n\t\"testing\"\n\t\"time\"\n\n")
	generation.mustWrite("\t%q\n", connectorImportPath)
	generation.mustWrite("\t\"github.com/superdurable/dex-connectors-library/sdkgo\"\n")
	generation.mustWrite("\t\"github.com/superdurable/dex-connectors-library/sdkgo/connectormock\"\n)\n\n")

	generation.mustWrite("// Mock is a scripted %s connection. Script each operation through its accessor.\n", manifest.Metadata.Name)
	generation.mustWrite("type Mock struct {\n\tconnection %s.Connection\n", connector)
	for _, operation := range manifest.Spec.Operations {
		generation.mustWrite("\t%s *connectormock.%s\n", lowerFirst(operation.GoName), mockGeneration.mockType(operation))
	}
	generation.mustWrite("}\n\n")

	generation.mustWrite("// New returns a mock connection named connectionName. Unscripted calls fail t, except a query's call that its\n")
	generation.mustWrite("// manifest default answers.\n")
	generation.mustWrite("func New(t testing.TB, connectionName string) *Mock {\n\tt.Helper()\n\tmock := &Mock{\n")
	for _, operation := range manifest.Spec.Operations {
		generation.mustWrite("\t\t%s: connectormock.New%s[%s.%s, %s.%s](t, %s.%sDefinition),\n", lowerFirst(operation.GoName), title(operation.Kind),
			connector, operation.InputType, connector, operation.OutputType, connector, operation.GoName)
	}
	generation.mustWrite("\t}\n")
	for _, operation := range manifest.Spec.Operations {
		if defaultMock(operation) != nil {
			generation.mustWrite("\tmock.%s.Default(%sDefault())\n", lowerFirst(operation.GoName), operation.GoName)
		}
	}
	generation.mustWrite("\tconnection, err := %s.NewConnectionWithOperations(mockOperations{mock: mock}, sdkgo.ConnectionRef{Provider: %s, Name: connectionName})\n",
		connector, strconv.Quote(manifest.Spec.Provider))
	generation.mustWrite("\tif err != nil {\n\t\tt.Fatalf(\"%s mock connection: %%v\", err)\n\t}\n", manifest.Metadata.Name)
	generation.mustWrite("\tmock.connection = connection\n\treturn mock\n}\n\n")
	generation.mustWrite("// Connection returns the typed connection to pass to the connector's Step factories.\n")
	generation.mustWrite("func (mock *Mock) Connection() %s.Connection { return mock.connection }\n\n", connector)
	for _, operation := range manifest.Spec.Operations {
		generation.mustWrite("// %s returns the %s script.\n", operation.GoName, operation.Name)
		generation.mustWrite("func (mock *Mock) %s() *connectormock.%s { return mock.%s }\n\n", operation.GoName, mockGeneration.mockType(operation), lowerFirst(operation.GoName))
	}
	generation.mustWrite("type mockOperations struct{ mock *Mock }\n\n")
	for _, operation := range manifest.Spec.Operations {
		generation.mustWrite("func (operations mockOperations) %s() sdkgo.%s[%s.%s, %s.%s] { return operations.mock.%s }\n",
			operation.GoName, title(operation.Kind), connector, operation.InputType, connector, operation.OutputType, lowerFirst(operation.GoName))
	}
	generation.mustWrite("\n")
	for _, operation := range manifest.Spec.Operations {
		if err := mockGeneration.writeOperationCases(generation, operation); err != nil {
			return nil, err
		}
	}
	formatted, err := format.Source(generation.output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated mock package: %w\n%s", err, generation.output.String())
	}
	return formatted, nil
}

func (mockGeneration *mockGenerator) writeOperationCases(generation *generator, operation schema.Operation) error {
	connector := mockGeneration.connectorPackage
	caseType := fmt.Sprintf("connectormock.Case[%s.%s]", connector, operation.OutputType)
	for _, branch := range operation.Branches {
		name := operation.GoName + branch.GoName
		if err := mockGeneration.claim(name); err != nil {
			return err
		}
		if branch.ID == "uncertain" {
			generation.mustWrite("// %s returns an uncertain %s outcome.\n", name, operation.Name)
			generation.mustWrite("func %s(value %s.%s, failure sdkgo.Failure) %s { return connectormock.Uncertain(value, failure) }\n\n",
				name, connector, operation.OutputType, caseType)
			continue
		}
		generation.mustWrite("// %s selects the %s branch: %s\n", name, branch.ID, commentText(branch.Description))
		generation.mustWrite("func %s(value %s.%s, failure *sdkgo.Failure) %s {\n\treturn connectormock.Branch(%s.%sBranch%s, value, failure)\n}\n\n",
			name, connector, operation.OutputType, caseType, connector, operation.GoName, branch.GoName)
	}
	retryName := operation.GoName + "Retry"
	if err := mockGeneration.claim(retryName); err != nil {
		return err
	}
	generation.mustWrite("// %s asks Dex to retry the %s Step, after the delay when it is positive.\n", retryName, operation.Name)
	generation.mustWrite("func %s(failure sdkgo.Failure, after time.Duration) %s {\n\treturn connectormock.Retry[%s.%s](failure, after)\n}\n\n",
		retryName, caseType, connector, operation.OutputType)
	for _, mock := range operation.Mocks {
		if err := mockGeneration.writeManifestMock(generation, operation, mock, caseType); err != nil {
			return err
		}
	}
	if defaulted := defaultMock(operation); defaulted != nil {
		name := operation.GoName + "Default"
		if err := mockGeneration.claim(name); err != nil {
			return err
		}
		generation.mustWrite("// %s is the manifest default, %s, which New installs.\n", name, defaulted.Name)
		generation.mustWrite("func %s() %s { return %s%s() }\n\n", name, caseType, operation.GoName, defaulted.GoName())
	}
	return nil
}

func (mockGeneration *mockGenerator) writeManifestMock(generation *generator, operation schema.Operation, mock schema.OperationMock, caseType string) error {
	connector := mockGeneration.connectorPackage
	name := operation.GoName + mock.GoName()
	if err := mockGeneration.claim(name); err != nil {
		return err
	}
	generation.mustWrite("// %s is the manifest mock %s: %s\n", name, mock.Name, commentText(mock.Description))
	generation.mustWrite("func %s() %s {\n", name, caseType)
	outputType := connector + "." + operation.OutputType
	switch {
	case mock.Retry != nil:
		after, err := mockRetryDelay(mock)
		if err != nil {
			return fmt.Errorf("operation %s mock %s: %w", operation.Name, mock.Name, err)
		}
		generation.mustWrite("\treturn connectormock.Retry[%s](%s, time.Duration(%d))\n", outputType, failureLiteral(mock.Retry.Failure), after)
	case mock.Uncertain != nil:
		writeMockValue(generation, outputType, mock.Uncertain.Output)
		generation.mustWrite("\treturn connectormock.Uncertain(value, %s)\n", failureLiteral(mock.Uncertain.Failure))
	case mock.Pages != nil:
		generation.mustWrite("\tpages := []%s{\n", outputType)
		for _, page := range mock.Pages {
			generation.mustWrite("\t\tconnectormock.MustDecodeOutput[%s](%s),\n", outputType, jsonLiteral(page.JSON()))
		}
		generation.mustWrite("\t}\n")
		generation.mustWrite("\tpageNumber := connectormock.CursorPageNumber[%s.%s](%s, %s, pages)\n", connector, operation.InputType,
			strconv.Quote(operation.Pagination.InputField), strconv.Quote(operation.Pagination.NextField))
		generation.mustWrite("\treturn connectormock.Paged(%s.%sBranch%s, pageNumber, pages...)\n", connector, operation.GoName, branchGoName(operation, mock.Branch))
	default:
		writeMockValue(generation, outputType, mock.Output)
		failure := "nil"
		if mock.Failure != nil {
			failure = "&" + failureLiteral(*mock.Failure)
		}
		generation.mustWrite("\treturn connectormock.Branch(%s.%sBranch%s, value, %s)\n", connector, operation.GoName, branchGoName(operation, mock.Branch), failure)
	}
	generation.mustWrite("}\n\n")
	return nil
}

func (mockGeneration *mockGenerator) generateTest(connectorImportPath string) ([]byte, error) {
	generation := &generator{}
	manifest := mockGeneration.manifest
	connector := mockGeneration.connectorPackage
	generation.mustWrite("// Code generated by connectorctl generate; DO NOT EDIT.\n")
	generation.mustWrite("// Copyright (c) 2026 Super Durable\n// SPDX-License-Identifier: MIT\n\n")
	generation.mustWrite("package %s\n\n", MockPackageName(manifest))
	generation.mustWrite("import (\n\t\"testing\"\n\n\t%q\n\t\"github.com/superdurable/dex-connectors-library/sdkgo/connectormock\"\n)\n\n", connectorImportPath)
	generation.mustWrite("func TestManifestMockOutputsDecodeStrictly(t *testing.T) {\n")
	generation.mustWrite("\tfixtures := []struct {\n\t\tname   string\n\t\tdecode func() error\n\t}{\n")
	for _, operation := range manifest.Spec.Operations {
		outputType := connector + "." + operation.OutputType
		for _, mock := range operation.Mocks {
			values := make([]string, 0, len(mock.Pages)+1)
			switch {
			case mock.Pages != nil:
				for _, page := range mock.Pages {
					values = append(values, page.JSON())
				}
			case mock.Output != nil:
				values = append(values, mock.Output.JSON())
			case mock.Uncertain != nil && mock.Uncertain.Output != nil:
				values = append(values, mock.Uncertain.Output.JSON())
			}
			for index, value := range values {
				generation.mustWrite("\t\t{name: %q, decode: func() error { _, err := connectormock.DecodeOutput[%s](%s); return err }},\n",
					fmt.Sprintf("%s/%s/%d", operation.Name, mock.Name, index+1), outputType, jsonLiteral(value))
			}
		}
	}
	generation.mustWrite("\t}\n\tfor _, fixture := range fixtures {\n")
	generation.mustWrite("\t\tif err := fixture.decode(); err != nil {\n\t\t\tt.Errorf(\"manifest mock %%s: %%v\", fixture.name, err)\n\t\t}\n\t}\n}\n\n")
	generation.mustWrite("func TestNewBindsEveryOperation(t *testing.T) {\n\tmock := New(t, \"mock\")\n")
	for _, operation := range manifest.Spec.Operations {
		generation.mustWrite("\tif mock.%s().Definition().Operation.OperationID != %q {\n\t\tt.Errorf(\"%s mock has another definition\")\n\t}\n",
			operation.GoName, operation.Name, operation.Name)
	}
	generation.mustWrite("}\n")
	formatted, err := format.Source(generation.output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated mock test: %w\n%s", err, generation.output.String())
	}
	return formatted, nil
}

func (mockGeneration *mockGenerator) mockType(operation schema.Operation) string {
	return fmt.Sprintf("%s[%s.%s, %s.%s]", title(operation.Kind), mockGeneration.connectorPackage, operation.InputType,
		mockGeneration.connectorPackage, operation.OutputType)
}

// claim reserves one generated identifier, because operation and mock names can concatenate to the same name.
func (mockGeneration *mockGenerator) claim(identifier string) error {
	if mockGeneration.identifiers[identifier] || identifier == "New" || identifier == "Mock" {
		return fmt.Errorf("generated mock identifier %s is declared twice; rename an operation or mock", identifier)
	}
	mockGeneration.identifiers[identifier] = true
	return nil
}

func writeMockValue(generation *generator, outputType string, value *schema.MockValue) {
	if value == nil {
		generation.mustWrite("\tvar value %s\n", outputType)
		return
	}
	generation.mustWrite("\tvalue := connectormock.MustDecodeOutput[%s](%s)\n", outputType, jsonLiteral(value.JSON()))
}

func failureLiteral(failure schema.MockFailure) string {
	return fmt.Sprintf("sdkgo.Failure{Kind: sdkgo.%s, Message: %s}", failureKindConstants[failure.Kind], strconv.Quote(failure.Message))
}

func mockRetryDelay(mock schema.OperationMock) (time.Duration, error) {
	if mock.Retry.After == "" {
		return 0, nil
	}
	return time.ParseDuration(mock.Retry.After)
}

func defaultMock(operation schema.Operation) *schema.OperationMock {
	for index := range operation.Mocks {
		if operation.Mocks[index].Default {
			return &operation.Mocks[index]
		}
	}
	return nil
}

func branchGoName(operation schema.Operation, branchID string) string {
	for _, branch := range operation.Branches {
		if branch.ID == branchID {
			return branch.GoName
		}
	}
	panic(fmt.Sprintf("validated mock names undeclared branch %s", branchID))
}

// MockPackageImportPath returns the mock package import path below a connector module path.
func MockPackageImportPath(manifest schema.Manifest, connectorModulePath string) string {
	return strings.TrimSuffix(connectorModulePath, "/") + "/" + MockPackageName(manifest)
}

func commentText(text string) string {
	return strings.Join(strings.Fields(text), " ")
}

// jsonLiteral returns a raw Go string literal for readable fixtures, or a quoted one when the JSON has a backquote.
func jsonLiteral(encoded string) string {
	if strings.Contains(encoded, "`") {
		return strconv.Quote(encoded)
	}
	return "`" + encoded + "`"
}
