// GenerateTypeScript writes the manifest-backed TypeScript contracts for supported operations.
func GenerateTypeScript(manifest schema.Manifest, goDirectory string, publishedModelNames ...string) (map[string][]byte, error) {
	if manifest.Spec.Languages == nil || manifest.Spec.Languages.TypeScript == nil {
		return nil, nil
	}
	selected := make(map[string]bool)
	for _, name := range manifest.Spec.Languages.TypeScript.Operations {
		selected[name] = true
	}
	var operations []schema.Operation
	var modelNames []string
	for _, operation := range manifest.Spec.Operations {
		if selected[operation.Name] {
			operations = append(operations, operation)
			modelNames = append(modelNames, operation.InputType, operation.OutputType)
		}
	}
	graph, err := gomodel.Load(goDirectory, modelNames, publishedModelNames...)
	if err != nil {
		return nil, err
	}
	files := make(map[string][]byte)
	files["models.ts"] = generateTypeScriptModels(manifest, graph.Models)
	definitions, err := generateTypeScriptDefinitions(manifest, operations)
	if err != nil {
		return nil, err
	}
	files["definitions.ts"] = definitions
	files["steps.ts"] = generateTypeScriptSteps(operations)
	mock, err := generateTypeScriptMock(manifest, operations, graph.Models)
	if err != nil {
		return nil, err
	}
	files["mock.ts"] = mock
	files["connection.ts"] = generateTypeScriptConnection(manifest, operations)
	for name, content := range files {
		files[name] = append(bytes.TrimRight(content, "\n"), '\n')
	}
	return files, nil
}

func typeScriptHeader() string {
	return "// Code generated by connectorctl generate; DO NOT EDIT.\n// Copyright (c) 2026 Super Durable\n// SPDX-License-Identifier: MIT\n\n"
}

func generateTypeScriptModels(manifest schema.Manifest, models []gomodel.Model) []byte {
	var output bytes.Buffer
	output.WriteString(typeScriptHeader())
	output.WriteString("import { z } from 'zod';\n")
	providerType := "CredentialProvider"
	if manifest.Spec.Auth.Refreshable {
		providerType = "RefreshingCredentialProvider"
	}
	usesSecretString := false
	for _, field := range manifest.Spec.Auth.Fields {
		usesSecretString = usesSecretString || field.Type == "secretString"
	}
	for _, method := range manifest.Spec.Auth.Methods {
		for _, field := range method.Fields {
			usesSecretString = usesSecretString || field.Type == "secretString"
		}
	}
	credentialImports := providerType
	if usesSecretString {
		credentialImports += ", SecretString"
	}
	if len(manifest.Spec.Auth.Methods) > 0 && usesSecretString {
		output.WriteString("import { SecretString } from '@superdurable/connectors-sdk';\n")
		credentialImports = providerType
	}
	output.WriteString("import type { " + credentialImports + " } from '@superdurable/connectors-sdk';\n\n")
	output.WriteString("/** Connector configuration; omitted fields use manifest defaults. */\nexport interface Config {\n")
	for _, field := range generatedConfigFields(manifest) {
		name := field.Name
		fieldType := "string"
		if field.Type == "integer" || field.Type == "number" || field.Type == "duration" {
			fieldType = "number"
		}
		if field.Type == "boolean" {
			fieldType = "boolean"
		}
		if field.Type == "stringList" {
			fieldType = "string[]"
		}
		if field.Type == "duration" {
			name += "Ms"
		}
		optional := "?"
		if field.Required {
			optional = ""
		}
		comment := field.Description
		if field.Type == "duration" {
			comment = strings.TrimSpace(comment) + " Runtime value in milliseconds."
		}
		fmt.Fprintf(&output, "  /** %s */\n  %s%s: %s;\n", typeScriptJSDoc(comment), name, optional, fieldType)
	}
	output.WriteString("}\n\n")
	output.WriteString("/** Runtime schema for manifest configuration. */\nexport const ConfigSchema = z.object({\n")
	for _, field := range generatedConfigFields(manifest) {
		name := field.Name
		expression := "z.string()"
		if field.Type == "integer" || field.Type == "duration" {
			expression = "z.number().int()"
		} else if field.Type == "number" {
			expression = "z.number()"
		} else if field.Type == "boolean" {
			expression = "z.boolean()"
		} else if field.Type == "stringList" {
			expression = "z.array(z.string())"
		}
		if field.Type == "duration" {
			name += "Ms"
		}
		if !field.Required {
			expression += ".optional()"
		}
		fmt.Fprintf(&output, "  %s: %s,\n", strconv.Quote(name), expression)
	}
	output.WriteString("});\n\n")
	allCredentialFields := make(map[string]schema.Field)
	credentialCounts := make(map[string]int)
	methodCount := len(manifest.Spec.Auth.Methods)
	if methodCount == 0 {
		methodCount = 1
		for _, field := range manifest.Spec.Auth.Fields {
			allCredentialFields[field.GoName] = field
			credentialCounts[field.GoName] = 1
		}
	} else {
		for _, method := range manifest.Spec.Auth.Methods {
			for _, field := range method.Fields {
				allCredentialFields[field.GoName] = field
				if field.Required {
					credentialCounts[field.GoName]++
				}
			}
		}
	}
	output.WriteString("/** Private connector credentials resolved by the host. */\nexport interface Credentials {\n")
	if len(manifest.Spec.Auth.Methods) > 0 {
		output.WriteString("  /** Selected authorization method. */\n  authMethodId?: string;\n")
	}
	var fieldNames []string
	for fieldName := range allCredentialFields {
		fieldNames = append(fieldNames, fieldName)
	}
	sort.Strings(fieldNames)
	for _, fieldName := range fieldNames {
		field := allCredentialFields[fieldName]
		fieldType := "string"
		if field.Type == "secretString" {
			fieldType = "SecretString"
		} else if field.Type == "integer" || field.Type == "duration" {
			fieldType = "number"
		} else if field.Type == "boolean" {
			fieldType = "boolean"
		} else if field.Type == "stringList" {
			fieldType = "string[]"
		} else if field.Type == "stringMap" {
			fieldType = "Record<string, string>"
		}
		optional := "?"
		if credentialCounts[fieldName] == methodCount && field.Required {
			optional = ""
		}
		fmt.Fprintf(&output, "  /** %s */\n  %s%s: %s;\n", typeScriptJSDoc(field.Description), typeScriptFieldName(field.Name), optional, fieldType)
	}
	output.WriteString("}\n\n")
	if len(manifest.Spec.Auth.Methods) > 0 {
		for _, fieldName := range fieldNames {
			if allCredentialFields[fieldName].Type == "url" {
				output.WriteString(`function isAbsoluteCredentialURL(value: string): boolean {
  if (value !== value.trim() || /[\u0000-\u001f\u007f]/.test(value) || /%(?![0-9a-fA-F]{2})/.test(value)) return false;
  const authority = value.match(/^[A-Za-z][A-Za-z0-9+.-]*:\/\/([^/?#]*)/)?.[1];
  if (!authority || /\s/.test(authority)) return false;
  const numericPort = authority.match(/:(\d+)$/);
  const parsedAuthority = numericPort && Number(numericPort[1]) > 65535 ? authority.replace(/:\d+$/, ':65535') : authority;
  const parsedValue = value.replace(authority, parsedAuthority);
  try { return !!new URL(parsedValue).hostname; } catch { return false; }
}

`)
				break
			}
		}
		writeTypeScriptCredentialDecoder(&output, manifest, allCredentialFields, fieldNames, false)
		if HasHostKeptCredentials(manifest) {
			writeTypeScriptCredentialDecoder(&output, manifest, allCredentialFields, fieldNames, true)
		}
	}
	fmt.Fprintf(&output, "/** Host-owned source of private connector credentials. */\nexport type CredentialSource = %s<Credentials>;\n\n", providerType)
	for _, model := range models {
		comment := "JSON model " + model.Name + " from the connector Go package."
		if model.Comment != "" {
			comment = model.Comment
		}
		fmt.Fprintf(&output, "/** %s */\nexport interface %s {\n", typeScriptJSDoc(comment), model.Name)
		for _, field := range model.Fields {
			optional := ""
			fieldType := typeScriptType(field.Type)
			if field.Optional {
				optional = "?"
				fieldType += " | undefined"
			}
			if field.Comment != "" {
				fmt.Fprintf(&output, "  /** %s */\n", typeScriptJSDoc(field.Comment))
			}
			fmt.Fprintf(&output, "  %s%s: %s;\n", strconv.Quote(field.Name), optional, fieldType)
		}
		output.WriteString("}\n")
	}
	output.WriteString("\n")
	for _, model := range models {
		isRecursive := typeScriptModelIsRecursive(model.Name, models)
		if isRecursive {
			fmt.Fprintf(&output, "/** Runtime validator for %s. */\nexport const %sSchema: z.ZodType<%s> = z.lazy(() => z.strictObject({\n", model.Name, model.Name, model.Name)
		} else {
			fmt.Fprintf(&output, "/** Runtime validator for %s. */\nexport const %sSchema = z.strictObject({\n", model.Name, model.Name)
		}
		for _, field := range model.Fields {
			schemaExpression := typeScriptSchema(field.Type)
			if field.Optional {
				schemaExpression += ".optional()"
			}
			fmt.Fprintf(&output, "  %s: %s,\n", strconv.Quote(field.Name), schemaExpression)
		}
		if isRecursive {
			output.WriteString("}));\n\n")
		} else {
			fmt.Fprintf(&output, "}) satisfies z.ZodType<%s>;\n\n", model.Name)
		}
	}
	return output.Bytes()
}

func typeScriptType(value gomodel.Type) string {
	var result string
	switch value.Kind {
	case gomodel.String, gomodel.Time, gomodel.Bytes:
		result = "string"
	case gomodel.Bool:
		result = "boolean"
	case gomodel.Int, gomodel.Int64, gomodel.Float:
		result = "number"
	case gomodel.Unknown:
		result = "unknown"
	case gomodel.List:
		result = "Array<" + typeScriptType(*value.Elem) + ">"
	case gomodel.Map:
		result = "{ [key: string]: " + typeScriptType(*value.Elem) + " }"
	case gomodel.Ref:
		result = value.Ref
	case gomodel.Enum:
		var literals []string
		for _, enumValue := range value.EnumValues {
			literals = append(literals, gomodel.EnumLiteral(enumValue, value.EnumBase))
		}
		if value.EnumBase == gomodel.String {
			result = strings.Join(literals, " | ") + " | (string & {})"
		} else {
			result = strings.Join(literals, " | ") + " | (number & {})"
		}
	}
	if value.Nullable {
		result += " | null"
	}
	return result
}

func typeScriptJSDoc(comment string) string {
	comment = strings.ReplaceAll(comment, "*/", "* /")
	lines := strings.Split(strings.TrimSpace(comment), "\n")
	for index, line := range lines {
		line = strings.TrimRight(line, " \t")
		if index > 0 {
			if line == "" {
				lines[index] = "   *"
				continue
			}
			lines[index] = "   * " + line
		}
	}
	return strings.Join(lines, "\n")
}

func typeScriptSchema(value gomodel.Type) string {
	var result string
	switch value.Kind {
	case gomodel.String:
		result = "z.string()"
	case gomodel.Bool:
		result = "z.boolean()"
	case gomodel.Int, gomodel.Int64:
		result = "z.number().int()"
	case gomodel.Float:
		result = "z.number()"
	case gomodel.Time:
		result = "z.iso.datetime({ offset: true })"
	case gomodel.Bytes:
		result = "z.base64()"
	case gomodel.Unknown:
		result = "z.unknown()"
	case gomodel.List:
		result = "z.array(" + typeScriptSchema(*value.Elem) + ")"
	case gomodel.Map:
		result = "z.record(z.string(), " + typeScriptSchema(*value.Elem) + ")"
	case gomodel.Ref:
		result = value.Ref + "Schema"
	case gomodel.Enum:
		if value.EnumBase == gomodel.String {
			result = "z.string()"
		} else {
			result = "z.number().int()"
		}
	}
	if value.Nullable {
		result += ".nullable()"
	}
	return result
}

func typeScriptFieldName(wireName string) string {
	if wireName == "" {
		return ""
	}
	parts := strings.FieldsFunc(wireName, func(character rune) bool { return character == '_' || character == '-' })
	if len(parts) == 0 {
		return ""
	}
	name := parts[0]
	for _, part := range parts[1:] {
		name += strings.ToUpper(part[:1]) + part[1:]
	}
	return name
}

func typeScriptCredentialValue(field schema.Field) string {
	fieldType := "string"
	switch field.Type {
	case "integer", "duration":
		fieldType = "number"
	case "boolean":
		fieldType = "boolean"
	case "stringList":
		fieldType = "string[]"
	case "stringMap":
		fieldType = "Record<string, string>"
	}
	value := "fields[" + strconv.Quote(field.Name) + "] as " + fieldType
	if field.Type == "secretString" {
		return "new SecretString(" + value + ")"
	}
	if field.Type == "stringList" {
		return "(" + value + ").map(item => item ?? '')"
	}
	if field.Type == "stringMap" {
		return "Object.fromEntries(Object.entries(" + value + ").map(([key, item]) => [key, item ?? '']))"
	}
	return value
}

func writeTypeScriptCredentialDecoder(output *bytes.Buffer, manifest schema.Manifest, allFields map[string]schema.Field, fieldNames []string, isShared bool) {
	name := "decodeCredentials"
	if isShared {
		name = "decodeSharedCredentials"
	}
	fmt.Fprintf(output, "/** Decode %s credential fields for the selected authorization method. */\nexport function %s(value: unknown): Credentials {\n", map[bool]string{false: "private", true: "shared"}[isShared], name)
	output.WriteString("  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new TypeError('credential fields are invalid');\n")
	output.WriteString("  const fields = value as { [key: string]: unknown };\n")
	output.WriteString("  const allowed = new Set([\"auth_method\"")
	for _, fieldName := range fieldNames {
		fmt.Fprintf(output, ", %s", strconv.Quote(allFields[fieldName].Name))
	}
	output.WriteString("]);\n  if (Object.keys(fields).some(key => !allowed.has(key))) throw new TypeError('stored credential does not match the connector credential fields');\n")
	for _, fieldName := range fieldNames {
		field := allFields[fieldName]
		value := "fields[" + strconv.Quote(field.Name) + "]"
		valid := "typeof " + value + " === 'string'"
		switch field.Type {
		case "integer", "duration":
			valid = "typeof " + value + " === 'number' && Number.isSafeInteger(" + value + ")"
		case "boolean":
			valid = "typeof " + value + " === 'boolean'"
		case "stringList":
			valid = "Array.isArray(" + value + ") && " + value + ".every(item => item === null || typeof item === 'string')"
		case "stringMap":
			valid = "!!" + value + " && typeof " + value + " === 'object' && !Array.isArray(" + value + ") && Object.values(" + value + ").every(item => item === null || typeof item === 'string')"
		}
		fmt.Fprintf(output, "  if (%s != null && !(%s)) throw new TypeError(%s);\n", value, valid, strconv.Quote("credential "+field.Name+" has an invalid type"))
	}
	output.WriteString("  const selectedMethod = fields['auth_method'] ?? '';\n")
	output.WriteString("  if (typeof selectedMethod !== 'string') throw new TypeError('credential auth_method is invalid');\n")
	fmt.Fprintf(output, "  const method = selectedMethod || %s;\n", strconv.Quote(manifest.Spec.Auth.DefaultMethod))
	output.WriteString("  const credentials = { authMethodId: method } as Credentials;\n")
	for index, method := range manifest.Spec.Auth.Methods {
		if index == 0 {
			fmt.Fprintf(output, "  if (method === %s) {\n", strconv.Quote(method.ID))
		} else {
			fmt.Fprintf(output, "  } else if (method === %s) {\n", strconv.Quote(method.ID))
		}
		sharedRequired := SharedRequiredCredentialFields(method)
		for _, field := range method.Fields {
			value := "fields[" + strconv.Quote(field.Name) + "]"
			isRequired := field.Required
			if isShared {
				isRequired = slices.Contains(sharedRequired, field.Name)
			}
			if isRequired {
				check := "!" + value
				message := "credential " + field.Name + " is required"
				if field.Type == "integer" || field.Type == "duration" {
					check = value + " == null || (" + value + " as number) <= 0"
					message = "credential " + field.Name + " must be positive"
				} else if field.Type == "stringList" || field.Type == "stringMap" {
					check = "!" + value + " || Object.keys(" + value + ").length === 0"
				}
				fmt.Fprintf(output, "    if (%s) throw new TypeError(%s);\n", check, strconv.Quote(message))
			}
			if field.Type == "integer" || field.Type == "duration" {
				fmt.Fprintf(output, "    if (%s != null && (%s as number) < 0) throw new TypeError(%s);\n", value, value, strconv.Quote("credential "+field.Name+" cannot be negative"))
			}
			if field.Type == "enum" {
				fmt.Fprintf(output, "    if (%s && !%s.includes(%s as string)) throw new TypeError(%s);\n", value, typeScriptStringArray(field.Enum), value, strconv.Quote("credential "+field.Name+" is invalid"))
			}
			if field.Type == "url" {
				fmt.Fprintf(output, "    if (%s && !isAbsoluteCredentialURL(%s as string)) throw new TypeError(%s);\n", value, value, strconv.Quote("credential "+field.Name+" must be an absolute URL"))
			}
			fmt.Fprintf(output, "    if (%s) credentials.%s = %s;\n", value, typeScriptFieldName(field.Name), typeScriptCredentialValue(field))
		}
	}
	output.WriteString("  } else {\n    throw new TypeError('credential auth_method is invalid');\n  }\n  return credentials;\n}\n\n")
}

func typeScriptStringArray(values []string) string {
	encoded, _ := json.Marshal(values)
	return string(encoded)
}

func generateTypeScriptDefinitions(manifest schema.Manifest, operations []schema.Operation) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(typeScriptHeader())
	if hasOperationKind(operations, "mutation") && hasOperationKind(operations, "query") {
		output.WriteString("import type { MutationDefinition, QueryDefinition } from '@superdurable/connectors-sdk';\n\n")
	} else if hasOperationKind(operations, "mutation") {
		output.WriteString("import type { MutationDefinition } from '@superdurable/connectors-sdk';\n\n")
	} else {
		output.WriteString("import type { QueryDefinition } from '@superdurable/connectors-sdk';\n\n")
	}
	fmt.Fprintf(&output, "/** Stable connector identity. */\nexport const ConnectorID = %s;\n", strconv.Quote(manifest.Metadata.Name))
	fmt.Fprintf(&output, "/** Provider identity for named connections. */\nexport const ProviderID = %s;\n\n", strconv.Quote(manifest.Spec.Provider))
	for _, operation := range operations {
		fmt.Fprintf(&output, "/** Branch IDs for %s. */\nexport const %sBranch = {\n", operation.Name, operation.GoName)
		for _, branch := range operation.Branches {
			fmt.Fprintf(&output, "  %s: %s,\n", branch.GoName, strconv.Quote(branch.ID))
		}
		output.WriteString("} as const;\n")
		for _, branch := range operation.Branches {
			fmt.Fprintf(&output, "/** %s */\nexport const %sBranch%s = %sBranch.%s;\n", typeScriptJSDoc(branch.Description), operation.GoName, branch.GoName, operation.GoName, branch.GoName)
		}
		definitionType := "QueryDefinition"
		if operation.Kind == "mutation" {
			definitionType = "MutationDefinition"
		}
		fmt.Fprintf(&output, "/** Manifest definition for %s. */\nexport const %sDefinition: %s = {\n", operation.Name, operation.GoName, definitionType)
		fmt.Fprintf(&output, "  operation: { connectorId: ConnectorID, operationId: %s },\n", strconv.Quote(operation.Name))
		output.WriteString("  branches: [\n")
		for _, branch := range operation.Branches {
			fmt.Fprintf(&output, "    { id: %s, description: %s", strconv.Quote(branch.ID), strconv.Quote(branch.Description))
			if branch.Optional {
				output.WriteString(", optional: true")
			}
			output.WriteString(" },\n")
		}
		output.WriteString("  ],\n")
		timeout, err := time.ParseDuration(operation.Execution.ExecuteMethodTimeout)
		if err != nil {
			return nil, fmt.Errorf("%s Execute timeout: %w", operation.Name, err)
		}
		fmt.Fprintf(&output, "  stepDefaults: { executeMethodTimeoutMs: %d, executeDurability: %s", timeout.Milliseconds(), strconv.Quote(operation.Execution.Durability))
		if retry := operation.Execution.Retry; retry != nil {
			initial, err := time.ParseDuration(retry.InitialInterval)
			if err != nil {
				return nil, err
			}
			maximum, err := time.ParseDuration(retry.MaximumInterval)
			if err != nil {
				return nil, err
			}
			total, err := time.ParseDuration(retry.TotalDuration)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&output, ", executeRetry: { initialIntervalMs: %d, backoffCoefficient: %s, maximumIntervalMs: %d, maximumAttempts: %d, totalDurationMs: %d }", initial.Milliseconds(), strconv.FormatFloat(retry.BackoffCoefficient, 'f', -1, 64), maximum.Milliseconds(), retry.MaximumAttempts, total.Milliseconds())
		}
		output.WriteString(" },\n};\n")
		fmt.Fprintf(&output, "/** Manifest metadata for %s. */\nexport const %sMetadata = { kind: %s, idempotency: %s, authorization: %s } as const;\n\n", operation.Name, operation.GoName, strconv.Quote(operation.Kind), strconv.Quote(operation.Idempotency), strconv.Quote(operation.Authorization))
	}
	return output.Bytes(), nil
}

func generateTypeScriptSteps(operations []schema.Operation) []byte {
	var output bytes.Buffer
	output.WriteString(typeScriptHeader())
	output.WriteString("import { goToBranch")
	if hasOperationKind(operations, "mutation") {
		output.WriteString(", newMutationStep, type Mutation, type MutationResult, type MutationStep, type MutationStepConfig")
	}
	if hasOperationKind(operations, "query") {
		output.WriteString(", newQueryStep, type Query, type QueryResult, type QueryStep, type QueryStepConfig")
	}
	output.WriteString(" } from '@superdurable/connectors-sdk';\n")
	output.WriteString("import type { StepTarget } from '@superdurable/dex';\n")
	output.WriteString("import type { Connection } from './connection.js';\n")
	var names []string
	for _, operation := range operations {
		names = append(names, operation.InputType, operation.OutputType)
	}
	output.WriteString("import type { " + strings.Join(uniqueStrings(names), ", ") + " } from './models.js';\n\n")
	for _, operation := range operations {
		kind := "Query"
		if operation.Kind == "mutation" {
			kind = "Mutation"
		}
		fmt.Fprintf(&output, "/** Configuration for the %s connector Step. */\nexport interface %sStepConfig<StepInput, OperationInput = %s, OperationOutput = %s> extends Omit<%sStepConfig<StepInput, OperationInput, OperationOutput>, 'operation' | 'connection' | 'branches'> {\n", operation.Name, operation.GoName, operation.InputType, operation.OutputType, kind)
		fmt.Fprintf(&output, "  /** Named connection supplying this operation. */\n  connection: Connection<{ %s(): %s<OperationInput, OperationOutput> }>;\n  /** Name matching the bound connection. */\n  connectionName: string;\n", operation.Name, kind)
		for _, branch := range operation.Branches {
			optional := ""
			if branch.Optional {
				optional = "?"
			}
			fmt.Fprintf(&output, "  /** %s */\n  %s%s: StepTarget<%sResult<OperationOutput>>;\n", typeScriptJSDoc(branch.Description), branch.ID, optional, kind)
		}
		output.WriteString("}\n\n")
		fmt.Fprintf(&output, "/** Build the %s Step from a named connection. */\nexport function new%sStep<StepInput, OperationInput = %s, OperationOutput = %s>(configuration: %sStepConfig<StepInput, OperationInput, OperationOutput>): %sStep<StepInput, OperationInput, OperationOutput> {\n", operation.Name, operation.GoName, operation.InputType, operation.OutputType, operation.GoName, kind)
		output.WriteString("  const { connection, connectionName, ")
		for _, branch := range operation.Branches {
			fmt.Fprintf(&output, "%s, ", branch.ID)
		}
		output.WriteString("...stepConfiguration } = configuration;\n")
		output.WriteString("  if (!connection || connection.reference.name !== connectionName) throw new TypeError('Step connection name differs from the bound connection');\n")
		operationAccessor := "connection.operations." + operation.Name + "()"
		fmt.Fprintf(&output, "  return new%sStep({ ...stepConfiguration, operation: %s, connection: connection.reference, branches: [\n", kind, operationAccessor)
		for _, branch := range operation.Branches {
			if branch.Optional {
				fmt.Fprintf(&output, "    ...(%s ? [goToBranch(%s, %s)] : []),\n", branch.ID, strconv.Quote(branch.ID), branch.ID)
			} else {
				fmt.Fprintf(&output, "    goToBranch(%s, %s),\n", strconv.Quote(branch.ID), branch.ID)
			}
		}
		output.WriteString("  ] });\n}\n\n")
	}
	return output.Bytes()
}

func generateTypeScriptConnection(manifest schema.Manifest, operations []schema.Operation) []byte {
	var output bytes.Buffer
	output.WriteString(typeScriptHeader())
	output.WriteString("import { ConnectionRefSchema, type ConnectionRef")
	if hasOperationKind(operations, "mutation") {
		output.WriteString(", type Mutation")
	}
	if hasOperationKind(operations, "query") {
		output.WriteString(", type Query")
	}
	output.WriteString(" } from '@superdurable/connectors-sdk';\n")
	output.WriteString("import type { LoadedProject } from '@superdurable/connectors-sdk/projectconfig';\n")
	var names []string
	for _, operation := range operations {
		names = append(names, operation.InputType, operation.OutputType)
	}
	output.WriteString("import type { " + strings.Join(uniqueStrings(names), ", ") + " } from './models.js';\n")
	output.WriteString("import { ConnectorID, ProviderID } from './definitions.js';\n\n")
	output.WriteString("/** Typed operations supplied by a client or mock. */\nexport interface Operations {\n")
	for _, operation := range operations {
		kind := "Query"
		if operation.Kind == "mutation" {
			kind = "Mutation"
		}
		fmt.Fprintf(&output, "  /** Invoke %s through this connection. */\n  %s(): %s<%s, %s>;\n", operation.Name, operation.Name, kind, operation.InputType, operation.OutputType)
	}
	output.WriteString("}\n\n")
	output.WriteString("/** Named connector connection kept outside Flow state. */\nexport class Connection<BoundOperations = Operations> {\n  /** Stable provider and connection name. */\n  readonly reference: ConnectionRef;\n  /** Bound provider operations. */\n  readonly operations: BoundOperations;\n\n  /** Validate a reference and bind operations. */\n  constructor(reference: ConnectionRef, operations: BoundOperations) {\n    this.reference = ConnectionRefSchema.parse(reference);\n")
	output.WriteString("    if (this.reference.provider !== ProviderID) throw new TypeError('connection provider differs from the manifest');\n    if (!operations) throw new TypeError('connector operations are required');\n    this.operations = operations;\n  }\n}\n\n")
	output.WriteString("/** Bind a client to a named connection. */\nexport function newConnection(client: Operations, reference: ConnectionRef): Connection {\n  if (!client) throw new TypeError('connector client is required');\n  return new Connection(reference, client);\n}\n\n")
	output.WriteString("/** Bind scripted operations to a named connection. */\nexport function newConnectionWithOperations(operations: Operations, reference: ConnectionRef): Connection {\n  return new Connection(reference, operations);\n}\n\n")
	output.WriteString("/** Resolve a named connection from a loaded Dex project. */\nexport function newProjectConnection(project: LoadedProject, connectionName: string, createClient: (project: LoadedProject, connectionName: string) => Operations): Connection {\n")
	output.WriteString("  if (!project) throw new TypeError('loaded project is required');\n")
	output.WriteString("  const reference = ConnectionRefSchema.parse({ provider: ProviderID, name: connectionName });\n")
	output.WriteString("  const selected = project.configuration.connections.find(entry => entry.connectorId === ConnectorID && entry.connectionName === connectionName);\n")
	output.WriteString("  if (!selected || selected.provider !== ProviderID) throw new TypeError('project connection is not configured');\n")
	output.WriteString("  return newConnection(createClient(project, connectionName), reference);\n}\n\n")
	fmt.Fprintf(&output, "/** Provider expected by named connections. */\nexport const ConnectionNameProvider = %s;\n", strconv.Quote(manifest.Spec.Provider))
	return output.Bytes()
}

func generateTypeScriptMock(manifest schema.Manifest, operations []schema.Operation, models []gomodel.Model) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString(typeScriptHeader())
	hasUncertain := false
	for _, operation := range operations {
		if operationHasBranch(operation, "uncertain") {
			hasUncertain = true
		}
		for _, mock := range operation.Mocks {
			if mock.Uncertain != nil {
				hasUncertain = true
			}
		}
	}
	if hasUncertain {
		output.WriteString("import { branchCase, retryCase, uncertainCase, type Case")
	} else {
		output.WriteString("import { branchCase, retryCase, type Case")
	}
	if hasOperationKind(operations, "mutation") {
		output.WriteString(", newMutation, type MockMutation")
	}
	if hasOperationKind(operations, "query") {
		output.WriteString(", newQuery, type MockQuery")
	}
	output.WriteString(" } from '@superdurable/connectors-sdk/connectormock';\n")
	output.WriteString("import type { Failure } from '@superdurable/connectors-sdk';\n")
	var allModelNames []string
	for _, model := range models {
		allModelNames = append(allModelNames, model.Name)
	}
	output.WriteString("import type { " + strings.Join(allModelNames, ", ") + " } from './models.js';\n")
	var schemaNames []string
	for _, model := range models {
		schemaNames = append(schemaNames, model.Name+"Schema")
	}
	output.WriteString("import { " + strings.Join(schemaNames, ", ") + " } from './models.js';\n")
	usesConnectorID := false
	for _, operation := range operations {
		for _, mock := range operation.Mocks {
			usesConnectorID = usesConnectorID || mock.Retry != nil || mock.Uncertain != nil || mock.Failure != nil
		}
	}
	output.WriteString("import { ProviderID")
	if usesConnectorID {
		output.WriteString(", ConnectorID")
	}
	for _, operation := range operations {
		fmt.Fprintf(&output, ", %sDefinition", operation.GoName)
	}
	output.WriteString(" } from './definitions.js';\n")
	output.WriteString("import { newConnectionWithOperations, type Connection, type Operations } from './connection.js';\n\n")
	modelByName := make(map[string]gomodel.Model, len(models))
	for _, model := range models {
		modelByName[model.Name] = model
	}
	for _, model := range models {
		fmt.Fprintf(&output, "/** Go zero value for %s in scripted cases. */\nexport const empty%s: %s = %sSchema.parse({\n", model.Name, model.Name, model.Name, model.Name)
		for _, field := range model.Fields {
			if field.Optional {
				continue
			}
			value := emptyTypeScriptValue(field.Type)
			fmt.Fprintf(&output, "  %s: %s,\n", strconv.Quote(field.Name), value)
		}
		output.WriteString("});\n")
	}
	output.WriteString("\n")
	for _, operation := range operations {
		for _, branch := range operation.Branches {
			if branch.ID == "uncertain" {
				continue
			}
			fmt.Fprintf(&output, "/** Script the %s branch. */\nexport function %s%s(value: %s, failure?: Failure): Case<%s> { return branchCase(%s, value, failure); }\n", branch.ID, operation.Name, branch.GoName, operation.OutputType, operation.OutputType, strconv.Quote(branch.ID))
		}
		fmt.Fprintf(&output, "/** Script a safe retry of %s. */\nexport function %sRetry(failure: Failure, retryAfterMs = 0): Case<%s> { return retryCase(failure, retryAfterMs); }\n", operation.Name, operation.Name, operation.OutputType)
		if operation.Kind == "mutation" && operationHasBranch(operation, "uncertain") {
			fmt.Fprintf(&output, "/** Script an uncertain %s attempt. */\nexport function %sUncertain(value: %s, failure: Failure): Case<%s> { return uncertainCase(value, failure); }\n", operation.Name, operation.Name, operation.OutputType, operation.OutputType)
		}
		for _, mock := range operation.Mocks {
			functionName := operation.Name + strings.ToUpper(mock.Name[:1]) + mock.Name[1:]
			fmt.Fprintf(&output, "/** Manifest scenario %s for %s. */\nexport function %s(): Case<%s> {\n", mock.Name, operation.Name, functionName, operation.OutputType)
			mockOutput := mock.Output
			if mock.Uncertain != nil && mock.Uncertain.Output != nil {
				mockOutput = mock.Uncertain.Output
			}
			if mock.Retry == nil && mockOutput != nil {
				canonicalOutput, err := canonicalizeTypeScriptMockOutput(mockOutput.JSON(), operation.OutputType, modelByName)
				if err != nil {
					return nil, fmt.Errorf("%s mock %s output: %w", operation.Name, mock.Name, err)
				}
				fmt.Fprintf(&output, "  const value = %sSchema.parse(%s);\n", operation.OutputType, canonicalOutput)
			} else if mock.Retry == nil {
				fmt.Fprintf(&output, "  const value = empty%s;\n", operation.OutputType)
			}
			if mock.Retry != nil {
				fmt.Fprintf(&output, "  return retryCase({ kind: %s, provider: ConnectorID, operation: %s, message: %s }", strconv.Quote(mock.Retry.Failure.Kind), strconv.Quote(operation.Name), strconv.Quote(mock.Retry.Failure.Message))
				if mock.Retry.After != "" {
					delay, err := time.ParseDuration(mock.Retry.After)
					if err != nil {
						return nil, fmt.Errorf("%s mock %s retryAfter: %w", operation.Name, mock.Name, err)
					}
					fmt.Fprintf(&output, ", %d", delay.Milliseconds())
				}
				output.WriteString(");\n")
			} else if mock.Uncertain != nil {
				fmt.Fprintf(&output, "  return uncertainCase(value, { kind: %s, provider: ConnectorID, operation: %s, message: %s });\n", strconv.Quote(mock.Uncertain.Failure.Kind), strconv.Quote(operation.Name), strconv.Quote(mock.Uncertain.Failure.Message))
			} else {
				fmt.Fprintf(&output, "  return branchCase(%s, value", strconv.Quote(mock.Branch))
				if mock.Failure != nil {
					fmt.Fprintf(&output, ", { kind: %s, provider: ConnectorID, operation: %s, message: %s }", strconv.Quote(mock.Failure.Kind), strconv.Quote(operation.Name), strconv.Quote(mock.Failure.Message))
				}
				output.WriteString(");\n")
			}
			output.WriteString("}\n")
			if mock.Default {
				fmt.Fprintf(&output, "/** Default %s scenario. */\nexport function %sDefault(): Case<%s> { return %s(); }\n", operation.Name, operation.Name, operation.OutputType, functionName)
			}
		}
		output.WriteString("\n")
	}
	output.WriteString("/** Scripted operations and manifest defaults for this connector. */\nexport class GeneratedMock implements Operations {\n")
	for _, operation := range operations {
		kind := "MockQuery"
		if operation.Kind == "mutation" {
			kind = "MockMutation"
		}
		fmt.Fprintf(&output, "  readonly #%s: %s<%s, %s>;\n", operation.Name, kind, operation.InputType, operation.OutputType)
	}
	output.WriteString("  readonly #connection: Connection;\n\n  constructor(connectionName: string) {\n")
	for _, operation := range operations {
		constructor := "newQuery"
		if operation.Kind == "mutation" {
			constructor = "newMutation"
		}
		field := "#" + operation.Name
		fmt.Fprintf(&output, "    this.%s = %s<%s, %s>(%sDefinition)", field, constructor, operation.InputType, operation.OutputType, operation.GoName)
		defaultScenario := false
		for _, mock := range operation.Mocks {
			if mock.Default {
				defaultScenario = true
				break
			}
		}
		if defaultScenario {
			fmt.Fprintf(&output, ".default(%sDefault())", operation.Name)
		}
		output.WriteString(";\n")
	}
	output.WriteString("    this.#connection = newConnectionWithOperations(this, { provider: ProviderID, name: connectionName });\n  }\n\n")
	output.WriteString("  connection(): Connection { return this.#connection; }\n")
	for _, operation := range operations {
		kind := "MockQuery"
		if operation.Kind == "mutation" {
			kind = "MockMutation"
		}
		fmt.Fprintf(&output, "  %s(): %s<%s, %s> { return this.#%s; }\n", operation.Name, kind, operation.InputType, operation.OutputType, operation.Name)
	}
	output.WriteString("  assertNoFailures(): void {\n")
	for _, operation := range operations {
		field := "#" + operation.Name
		fmt.Fprintf(&output, "    this.%s.assertNoFailures();\n", field)
	}
	output.WriteString("  }\n}\n")
	return output.Bytes(), nil
}

func emptyTypeScriptValue(value gomodel.Type) string {
	if value.Nullable && value.Kind != gomodel.List && value.Kind != gomodel.Map && value.Kind != gomodel.Bytes {
		return "null"
	}
	switch value.Kind {
	case gomodel.String, gomodel.Bytes:
		return "''"
	case gomodel.Bool:
		return "false"
	case gomodel.Int, gomodel.Int64, gomodel.Float:
		return "0"
	case gomodel.Time:
		return "'0001-01-01T00:00:00Z'"
	case gomodel.List:
		return "[]"
	case gomodel.Map:
		return "{}"
	case gomodel.Ref:
		return "empty" + value.Ref
	case gomodel.Enum:
		if value.EnumBase == gomodel.String {
			return "''"
		}
		return "0"
	case gomodel.Unknown:
		return "null"
	}
	return "null"
}

func typeScriptModelIsRecursive(name string, models []gomodel.Model) bool {
	byName := make(map[string]gomodel.Model, len(models))
	for _, model := range models {
		byName[model.Name] = model
	}
	visited := map[string]bool{}
	var reachesStart func(string) bool
	reachesStart = func(current string) bool {
		if visited[current] {
			return false
		}
		visited[current] = true
		for _, field := range byName[current].Fields {
			var visitType func(gomodel.Type) bool
			visitType = func(value gomodel.Type) bool {
				if value.Kind == gomodel.Ref {
					return value.Ref == name || reachesStart(value.Ref)
				}
				if value.Elem != nil {
					return visitType(*value.Elem)
				}
				return false
			}
			if visitType(field.Type) {
				return true
			}
		}
		return false
	}
	return reachesStart(name)
}

func canonicalizeTypeScriptMockOutput(encoded, modelName string, models map[string]gomodel.Model) (string, error) {
	decoder := json.NewDecoder(strings.NewReader(encoded))
	decoder.UseNumber()
	var value any
	if err := decoder.Decode(&value); err != nil {
		return "", err
	}
	canonical := canonicalizeTypeScriptMockValue(value, gomodel.Type{Kind: gomodel.Ref, Ref: modelName}, models)
	contents, err := json.Marshal(canonical)
	if err != nil {
		return "", err
	}
	return string(contents), nil
}

func canonicalizeTypeScriptMockValue(value any, modelType gomodel.Type, models map[string]gomodel.Model) any {
	switch modelType.Kind {
	case gomodel.Ref:
		fields, ok := value.(map[string]any)
		if !ok {
			return value
		}
		model, ok := models[modelType.Ref]
		if !ok {
			return value
		}
		canonical := make(map[string]any, len(fields))
		for _, field := range model.Fields {
			fieldValue, present := fields[field.Name]
			if !present {
				for suppliedName, suppliedValue := range fields {
					if strings.EqualFold(suppliedName, field.Name) {
						fieldValue, present = suppliedValue, true
						break
					}
				}
			}
			if present {
				canonical[field.Name] = canonicalizeTypeScriptMockValue(fieldValue, field.Type, models)
			} else if !field.Optional {
				canonical[field.Name] = zeroGoJSONValue(field.Type, models)
			}
		}
		return canonical
	case gomodel.List:
		items, ok := value.([]any)
		if !ok {
			return value
		}
		for index, item := range items {
			items[index] = canonicalizeTypeScriptMockValue(item, *modelType.Elem, models)
		}
		return items
	case gomodel.Map:
		entries, ok := value.(map[string]any)
		if !ok {
			return value
		}
		for name, entry := range entries {
			entries[name] = canonicalizeTypeScriptMockValue(entry, *modelType.Elem, models)
		}
		return entries
	}
	return value
}

func zeroGoJSONValue(modelType gomodel.Type, models map[string]gomodel.Model) any {
	if modelType.Nullable {
		return nil
	}
	switch modelType.Kind {
	case gomodel.String, gomodel.Enum:
		if modelType.Kind == gomodel.Enum && modelType.EnumBase != gomodel.String {
			return 0
		}
		return ""
	case gomodel.Bool:
		return false
	case gomodel.Int, gomodel.Int64, gomodel.Float:
		return 0
	case gomodel.Time:
		return "0001-01-01T00:00:00Z"
	case gomodel.List:
		return []any{}
	case gomodel.Map:
		return map[string]any{}
	case gomodel.Ref:
		value := map[string]any{}
		for _, field := range models[modelType.Ref].Fields {
			if !field.Optional {
				value[field.Name] = zeroGoJSONValue(field.Type, models)
			}
		}
		return value
	}
	return nil
}

func operationHasBranch(operation schema.Operation, branchID string) bool {
	for _, branch := range operation.Branches {
		if branch.ID == branchID {
			return true
		}
	}
	return false
}

func hasOperationKind(operations []schema.Operation, kind string) bool {
	for _, operation := range operations {
		if operation.Kind == kind {
			return true
		}
	}
	return false
}

func uniqueStrings(values []string) []string {
	seen := make(map[string]bool)
	var result []string
	for _, value := range values {
		if !seen[value] {
			result = append(result, value)
			seen[value] = true
		}
	}
	return result
}

// TypeScriptGeneratedPath returns the checked-in location of a generated TypeScript file.
func TypeScriptGeneratedPath(manifestPath, name string) string {
	return filepath.Join(filepath.Dir(manifestPath), "typescript", "src", "generated", name)
}
