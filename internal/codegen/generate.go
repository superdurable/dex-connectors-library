func Generate(manifest schema.Manifest) ([]byte, error) {
	var output bytes.Buffer
	write := func(format string, values ...any) { fmt.Fprintf(&output, format, values...) }
	write("// Code generated by connectorctl generate; DO NOT EDIT.\n")
	write("// Copyright (c) 2026 Super Durable\n// SPDX-License-Identifier: MIT\n\n")
	write("package %s\n\n", manifest.Spec.Codegen.Go.Package)
	write("import (\n\t\"fmt\"\n")
	if hasFieldType(manifest, "url") {
		write("\t\"net/url\"\n")
	}
	write("\t\"time\"\n\n")
	write("\tconnector \"github.com/superdurable/dex-connectors-library/sdk/go\"\n")
	write("\t\"github.com/superdurable/dex/sdk-go/dex\"\n)\n\n")
	write("const (\n\tConnectorID = %s\n\tConnectorVersion = %s\n)\n\n", strconv.Quote(manifest.Metadata.Name), strconv.Quote(manifest.Metadata.Version))
	for _, field := range append(append([]schema.Field(nil), manifest.Spec.Configuration.Fields...), manifest.Spec.Auth.Fields...) {
		if field.Type != "enum" {
			continue
		}
		seenConstants := map[string]bool{}
		for _, value := range field.Enum {
			name := enumIdentifier(value)
			if seenConstants[name] {
				return nil, fmt.Errorf("enum field %s has colliding Go values", field.Name)
			}
			seenConstants[name] = true
		}
		write("type %s string\n\nconst (\n", field.GoName)
		for _, value := range field.Enum {
			write("\t%s%s %s = %s\n", field.GoName, enumIdentifier(value), field.GoName, strconv.Quote(value))
		}
		write(")\n\n")
	}

	write("type Config struct {\n")
	for _, field := range manifest.Spec.Configuration.Fields {
		write("\t%s %s `json:\"%s,omitempty\" yaml:\"%s,omitempty\"`\n", field.GoName, goType(field), field.Name, field.Name)
	}
	write("}\n\n")
	write("type Credentials struct {\n")
	for _, field := range manifest.Spec.Auth.Fields {
		write("\t%s %s\n", field.GoName, goType(field))
	}
	write("}\n\n")

	write("func DefaultConfig() Config {\n\treturn Config{\n")
	for _, field := range manifest.Spec.Configuration.Fields {
		if field.Default != nil {
			literal, err := defaultLiteral(field)
			if err != nil {
				return nil, err
			}
			write("\t\t%s: %s,\n", field.GoName, literal)
		}
	}
	write("\t}\n}\n\n")
	write("func withConfigDefaults(config Config) Config {\n")
	if hasDefaults(manifest.Spec.Configuration.Fields) {
		write("\tdefaults := DefaultConfig()\n")
	}
	for _, field := range manifest.Spec.Configuration.Fields {
		if field.Default != nil {
			write("\tif %s { config.%s = defaults.%s }\n", zeroExpression("config."+field.GoName, field), field.GoName, field.GoName)
		}
	}
	write("\treturn config\n}\n\n")

	write("func (config Config) Validate() error {\n")
	for _, field := range manifest.Spec.Configuration.Fields {
		writeFieldValidation(&output, "config."+field.GoName, field, "configuration")
	}
	write("\treturn nil\n}\n\n")
	write("func (credentials Credentials) Validate() error {\n")
	for _, field := range manifest.Spec.Auth.Fields {
		writeFieldValidation(&output, "credentials."+field.GoName, field, "credential")
	}
	write("\treturn nil\n}\n\n")

	for _, operation := range manifest.Spec.Operations {
		for _, branch := range operation.Branches {
			write("const %sBranch%s connector.BranchID = %s\n", operation.GoName, branch.GoName, strconv.Quote(branch.ID))
		}
		write("\nvar %sDefinition = connector.%sDefinition{\n", operation.GoName, title(operation.Kind))
		write("\tOperation: connector.OperationRef{ConnectorID: ConnectorID, OperationID: %s},\n", strconv.Quote(operation.Name))
		write("\tBranches: []connector.BranchDefinition{\n")
		for _, branch := range operation.Branches {
			write("\t\t{ID: %sBranch%s, Description: %s},\n", operation.GoName, branch.GoName, strconv.Quote(branch.Description))
		}
		write("\t},\n\tDefectBranch: %s,\n", branchConstant(operation, operation.DefectBranch))
		if operation.Kind == "mutation" {
			write("\tUncertainBranch: %s,\n", branchConstant(operation, operation.UncertainBranch))
		}
		timeout, _ := time.ParseDuration(operation.Execution.ExecuteMethodTimeout)
		heartbeat, _ := time.ParseDuration(operation.Execution.HeartbeatTimeout)
		initial, _ := time.ParseDuration(operation.Execution.Retry.InitialInterval)
		maximum, _ := time.ParseDuration(operation.Execution.Retry.MaximumInterval)
		total, _ := time.ParseDuration(operation.Execution.Retry.TotalDuration)
		durability := "dex.StepDurabilitySync"
		if operation.Execution.Durability == "async" {
			durability = "dex.StepDurabilityAsync"
		}
		write("\tStepDefaults: connector.StepDefaults{\n")
		write("\t\tExecuteMethodTimeout: time.Duration(%d), HeartbeatTimeout: time.Duration(%d),\n", timeout, heartbeat)
		write("\t\tExecuteRetry: &dex.RetryPolicy{InitialInterval: time.Duration(%d), BackoffCoefficient: %s, MaximumInterval: time.Duration(%d), MaximumAttempts: %d, TotalDuration: time.Duration(%d)},\n", initial, strconv.FormatFloat(operation.Execution.Retry.BackoffCoefficient, 'f', -1, 64), maximum, operation.Execution.Retry.MaximumAttempts, total)
		write("\t\tExecuteDurability: %s,\n\t},\n", durability)
		write("\tResultAttribute: connector.Requirement%s,\n", title(operation.ResultAttribute))
		write("\tProgress: connector.ProgressCapabilities{Structured: %t, Text: %t},\n", contains(operation.Progress, "structured"), contains(operation.Progress, "text"))
		write("}\n\n")
	}

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated connector: %w\n%s", err, output.String())
	}
	return formatted, nil
}

func goType(field schema.Field) string {
	switch field.Type {
	case "integer":
		return "int64"
	case "boolean":
		return "bool"
	case "duration":
		return "time.Duration"
	case "stringList":
		return "[]string"
	case "stringMap":
		return "map[string]string"
	case "secretString":
		return "connector.SecretString"
	case "enum":
		return field.GoName
	default:
		return "string"
	}
}

func defaultLiteral(field schema.Field) (string, error) {
	switch field.Type {
	case "string", "url":
		value, ok := field.Default.(string)
		if !ok {
			return "", fmt.Errorf("%s default must be a string", field.Name)
		}
		return strconv.Quote(value), nil
	case "enum":
		value, ok := field.Default.(string)
		if !ok {
			return "", fmt.Errorf("%s default must be a string", field.Name)
		}
		return fmt.Sprintf("%s(%s)", field.GoName, strconv.Quote(value)), nil
	case "duration":
		value, ok := field.Default.(string)
		if !ok {
			return "", fmt.Errorf("%s default must be a duration", field.Name)
		}
		duration, err := time.ParseDuration(value)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("time.Duration(%d)", duration), nil
	case "integer":
		switch value := field.Default.(type) {
		case int:
			return strconv.Itoa(value), nil
		case int64:
			return strconv.FormatInt(value, 10), nil
		case uint64:
			return strconv.FormatUint(value, 10), nil
		}
		return "", fmt.Errorf("%s default must be an integer", field.Name)
	case "boolean":
		value, ok := field.Default.(bool)
		if !ok {
			return "", fmt.Errorf("%s default must be boolean", field.Name)
		}
		return strconv.FormatBool(value), nil
	case "stringList":
		values, ok := stringSlice(field.Default)
		if !ok {
			return "", fmt.Errorf("%s default must be a string list", field.Name)
		}
		quoted := make([]string, len(values))
		for index, value := range values {
			quoted[index] = strconv.Quote(value)
		}
		return "[]string{" + strings.Join(quoted, ", ") + "}", nil
	case "stringMap":
		values, ok := stringMap(field.Default)
		if !ok {
			return "", fmt.Errorf("%s default must be a string map", field.Name)
		}
		keys := make([]string, 0, len(values))
		for key := range values {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		entries := make([]string, 0, len(keys))
		for _, key := range keys {
			entries = append(entries, strconv.Quote(key)+": "+strconv.Quote(values[key]))
		}
		return "map[string]string{" + strings.Join(entries, ", ") + "}", nil
	default:
		return "", fmt.Errorf("%s default type %s is not supported", field.Name, field.Type)
	}
}

func zeroExpression(name string, field schema.Field) string {
	switch field.Type {
	case "stringList", "stringMap":
		return name + " == nil"
	case "string", "url", "enum":
		return name + " == \"\""
	case "boolean":
		return "!" + name
	default:
		return name + " == 0"
	}
}

func writeFieldValidation(output *bytes.Buffer, name string, field schema.Field, prefix string) {
	if field.Required {
		switch field.Type {
		case "secretString":
			fmt.Fprintf(output, "\tif %s.Reveal() == \"\" { return fmt.Errorf(%q) }\n", name, prefix+" "+field.Name+" is required")
		case "stringList", "stringMap":
			fmt.Fprintf(output, "\tif len(%s) == 0 { return fmt.Errorf(%q) }\n", name, prefix+" "+field.Name+" is required")
		case "integer", "duration":
			fmt.Fprintf(output, "\tif %s <= 0 { return fmt.Errorf(%q) }\n", name, prefix+" "+field.Name+" must be positive")
		default:
			fmt.Fprintf(output, "\tif %s == \"\" { return fmt.Errorf(%q) }\n", name, prefix+" "+field.Name+" is required")
		}
	}
	if field.Type == "url" {
		fmt.Fprintf(output, "\tif %s != \"\" { parsed, err := url.Parse(%s); if err != nil || parsed.Scheme == \"\" || parsed.Hostname() == \"\" { return fmt.Errorf(%q) } }\n", name, name, prefix+" "+field.Name+" must be an absolute URL")
	}
	if field.Type == "integer" || field.Type == "duration" {
		fmt.Fprintf(output, "\tif %s < 0 { return fmt.Errorf(%q) }\n", name, prefix+" "+field.Name+" cannot be negative")
	}
	if field.Type == "enum" {
		fmt.Fprintf(output, "\tswitch %s {\n\tcase \"\"", name)
		for _, value := range field.Enum {
			fmt.Fprintf(output, ", %s", strconv.Quote(value))
		}
		fmt.Fprintf(output, ":\n\tdefault: return fmt.Errorf(%q)\n\t}\n", prefix+" "+field.Name+" is invalid")
	}
}

func branchConstant(operation schema.Operation, id string) string {
	for _, branch := range operation.Branches {
		if branch.ID == id {
			return operation.GoName + "Branch" + branch.GoName
		}
	}
	return strconv.Quote(id)
}

func contains(values []string, expected string) bool {
	for _, value := range values {
		if value == expected {
			return true
		}
	}
	return false
}

func hasFieldType(manifest schema.Manifest, fieldType string) bool {
	for _, field := range manifest.Spec.Configuration.Fields {
		if field.Type == fieldType {
			return true
		}
	}
	for _, field := range manifest.Spec.Auth.Fields {
		if field.Type == fieldType {
			return true
		}
	}
	return false
}

func hasDefaults(fields []schema.Field) bool {
	for _, field := range fields {
		if field.Default != nil {
			return true
		}
	}
	return false
}

func enumIdentifier(value string) string {
	var output strings.Builder
	upper := true
	for _, character := range value {
		if !unicode.IsLetter(character) && !unicode.IsDigit(character) {
			upper = true
			continue
		}
		if upper {
			character = unicode.ToUpper(character)
			upper = false
		}
		output.WriteRune(character)
	}
	identifier := output.String()
	if identifier == "" {
		return "Value"
	}
	if unicode.IsDigit([]rune(identifier)[0]) {
		return "Value" + identifier
	}
	return identifier
}

func stringSlice(value any) ([]string, bool) {
	switch values := value.(type) {
	case []string:
		return append([]string(nil), values...), true
	case []any:
		result := make([]string, len(values))
		for index, item := range values {
			typed, ok := item.(string)
			if !ok {
				return nil, false
			}
			result[index] = typed
		}
		return result, true
	default:
		return nil, false
	}
}

func stringMap(value any) (map[string]string, bool) {
	switch values := value.(type) {
	case map[string]string:
		result := make(map[string]string, len(values))
		for key, item := range values {
			result[key] = item
		}
		return result, true
	case map[string]any:
		result := make(map[string]string, len(values))
		for key, item := range values {
			typed, ok := item.(string)
			if !ok {
				return nil, false
			}
			result[key] = typed
		}
		return result, true
	default:
		return nil, false
	}
}

func title(value string) string {
	if value == "" {
		return ""
	}
	return strings.ToUpper(value[:1]) + value[1:]
}
