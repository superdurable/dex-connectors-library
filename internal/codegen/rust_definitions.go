package codegen

import (
	"bytes"
	"fmt"
	"slices"
	"strings"

	"github.com/superdurable/dex-connectors-library/schema"
)

// GenerateRustDefinitions emits operation definitions for the Rust capabilities selected in the manifest.
func GenerateRustDefinitions(manifest schema.Manifest, operationNames []string) ([]byte, error) {
	var output bytes.Buffer
	output.WriteString("// Code generated by connectorctl. DO NOT EDIT.\n\nuse dex_connectors_sdk as sdk;\nuse std::time::Duration;\n")
	for _, operation := range manifest.Spec.Operations {
		if !slices.Contains(operationNames, operation.Name) {
			continue
		}
		durations, err := parseOperationDurations(operation)
		if err != nil {
			return nil, err
		}
		definition := title(operation.Kind) + "Definition"
		// Keep the Go name as a Rust type identifier even for initialisms in operation IDs.
		fmt.Fprintf(&output, "\npub struct %s;\n\nimpl %s {\n    pub fn definition() -> sdk::%s {\n        sdk::%s {\n", operation.GoName, operation.GoName, definition, definition)
		fmt.Fprintf(&output, "            operation: sdk::OperationRef::new(%s, %s),\n", rustLiteral(manifest.Metadata.Name), rustLiteral(operation.Name))
		output.WriteString("            branches: Some(vec![\n")
		for _, branch := range operation.Branches {
			fmt.Fprintf(&output, "                sdk::BranchDefinition::new(%s, %s, %t),\n", rustLiteral(branch.ID), rustLiteral(branch.Description), branch.Optional)
		}
		output.WriteString("            ]),\n            step_defaults: sdk::StepDefaults {\n")
		fmt.Fprintf(&output, "                execute_method_timeout: Duration::from_nanos(%d),\n", durations.executeMethodTimeout)
		fmt.Fprintf(&output, "                heartbeat_timeout: Duration::from_nanos(%d),\n", durations.heartbeatTimeout)
		fmt.Fprintf(&output, "                execute_durability: sdk::ExecuteDurability::%s,\n", title(operation.Execution.Durability))
		if retry := operation.Execution.Retry; retry == nil {
			output.WriteString("                execute_retry: Some(sdk::default_connector_step_execute_retry_policy()),\n")
		} else {
			fmt.Fprintf(&output, "                execute_retry: Some(sdk::RetryPolicy { initial_interval: Duration::from_nanos(%d), backoff_coefficient: %g_f64, maximum_interval: Duration::from_nanos(%d), maximum_attempts: %d, total_duration: Duration::from_nanos(%d) }),\n", durations.retryInitialInterval, retry.BackoffCoefficient, durations.retryMaximumInterval, retry.MaximumAttempts, durations.retryTotalDuration)
		}
		output.WriteString("            },\n")
		if operation.Kind == "mutation" {
			fmt.Fprintf(&output, "            repeat_on_unknown: Some(sdk::RepeatOnUnknown::%s),\n            max_sends: %d,\n", title(operation.ResolvedRepeatOnUnknown()), operation.ResolvedMaxSends())
		}
		output.WriteString("        }\n    }\n}\n")
	}
	return output.Bytes(), nil
}

func rustLiteral(value string) string {
	delimiter := ""
	for strings.Contains(value, `"`+delimiter) {
		delimiter += "#"
	}
	return "r" + delimiter + `"` + value + `"` + delimiter
}
