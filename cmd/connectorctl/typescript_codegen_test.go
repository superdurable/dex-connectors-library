package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/superdurable/dex-connectors-library/schema"
)

func TestTypeScriptGenerationRejectsPublishedExternalNameCollision(t *testing.T) {
	fixture, err := filepath.Abs(filepath.Join("..", "..", "internal", "codegen", "gomodel", "testdata", "models"))
	if err != nil {
		t.Fatal(err)
	}
	connector := t.TempDir()
	if err := os.Symlink(fixture, filepath.Join(connector, "go")); err != nil {
		t.Fatal(err)
	}
	modelsPath := filepath.Join(connector, "typescript", "src", "generated", "models.ts")
	if err := os.MkdirAll(filepath.Dir(modelsPath), 0o755); err != nil {
		t.Fatal(err)
	}
	previous := []byte("// Code generated by connectorctl generate; DO NOT EDIT.\nexport interface v1Item {\n}\n")
	if err := os.WriteFile(modelsPath, previous, 0o644); err != nil {
		t.Fatal(err)
	}
	manifest := schema.Manifest{Spec: schema.Spec{
		Languages: &schema.Languages{TypeScript: &schema.LanguagePackage{Operations: []string{"first", "second"}}},
		Operations: []schema.Operation{
			{Name: "first", InputType: "ExternalFirstItem", OutputType: "ExternalFirstItem"},
			{Name: "second", InputType: "ExternalSameName", OutputType: "ExternalSameName"},
		},
	}}
	_, err = generatedTypeScriptFiles(filepath.Join(connector, "connector.yaml"), manifest)
	if err == nil || !strings.Contains(err.Error(), `Go model name "v1Item" conflicts`) || !strings.Contains(err.Error(), "published type") {
		t.Fatalf("generation must reject a published-name collision, got %v", err)
	}
	current, err := os.ReadFile(modelsPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(current) != string(previous) {
		t.Fatalf("failed generation modified published models: %s", current)
	}
}
