package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"github.com/superdurable/dex-connectors-library/internal/codegen"
	"github.com/superdurable/dex-connectors-library/schema"
)

func generatedTypeScriptFiles(manifestPath string, manifest schema.Manifest) (map[string][]byte, error) {
	files := make(map[string][]byte)
	if manifest.Spec.Languages == nil || manifest.Spec.Languages.TypeScript == nil {
		return files, nil
	}
	goDirectory := filepath.Join(filepath.Dir(manifestPath), "go")
	hasAuthoredGoTypes, err := hasAuthoredGoSource(goDirectory)
	if err != nil {
		return nil, err
	}
	if !hasAuthoredGoTypes {
		// Language-manifest fixtures omit authored Go models; real TypeScript packages must provide them.
		if _, err := os.Stat(filepath.Join(filepath.Dir(manifestPath), "typescript", "src", "index.ts")); err == nil {
			return nil, fmt.Errorf("TypeScript connector requires authored Go operation types in %s", goDirectory)
		} else if !os.IsNotExist(err) {
			return nil, err
		}
		return files, nil
	}
	publishedNames, err := publishedTypeScriptModelNames(codegen.TypeScriptGeneratedPath(manifestPath, "models.ts"))
	if err != nil {
		return nil, err
	}
	generated, err := codegen.GenerateTypeScript(manifest, goDirectory, publishedNames...)
	if err != nil {
		return nil, err
	}
	for name, content := range generated {
		files[codegen.TypeScriptGeneratedPath(manifestPath, name)] = content
	}
	return files, nil
}

func hasAuthoredGoSource(goDirectory string) (bool, error) {
	goFiles, err := filepath.Glob(filepath.Join(goDirectory, "*.go"))
	if err != nil {
		return false, err
	}
	for _, goFile := range goFiles {
		if filepath.Base(goFile) != codegen.OutputFile {
			return true, nil
		}
	}
	return false, nil
}

func publishedTypeScriptModelNames(path string) ([]string, error) {
	contents, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read existing TypeScript models: %w", err)
	}
	var names []string
	for _, line := range bytes.Split(contents, []byte{'\n'}) {
		declaration, ok := bytes.CutPrefix(line, []byte("export interface "))
		if !ok {
			continue
		}
		name, ok := bytes.CutSuffix(declaration, []byte(" {"))
		if ok {
			names = append(names, string(name))
		}
	}
	return names, nil
}

func staleTypeScriptFiles(manifestPath string, generated map[string][]byte) ([]string, error) {
	directory := filepath.Join(filepath.Dir(manifestPath), "typescript", "src", "generated")
	entries, err := os.ReadDir(directory)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read generated TypeScript directory: %w", err)
	}
	var stale []string
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".ts" {
			continue
		}
		path := filepath.Join(directory, entry.Name())
		if _, ok := generated[path]; !ok {
			content, err := os.ReadFile(path)
			if err != nil {
				return nil, err
			}
			if bytes.HasPrefix(content, []byte("// Code generated by connectorctl generate; DO NOT EDIT.")) {
				stale = append(stale, path)
			}
		}
	}
	return stale, nil
}
